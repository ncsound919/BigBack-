        "    merged = {**row, **patch, 'id': row_id}",
        "    _table(name)[row_id] = merged",
        "    return merged",
        "",
        "def delete_row(name: str, row_id: str) -> bool:",
        "    return _table(name).pop(row_id, None) is not None",
