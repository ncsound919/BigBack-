def ts_pkg(project: str, deps: Dict[str, str], dev: Dict[str, str], scripts: Dict[str, str]) -> str:
    return json.dumps({
        "name": project,
        "version": "0.1.0",
        "private": True,
        "type": "module",
        "scripts": scripts,
        "dependencies": deps,
        "devDependencies": dev,
    }, indent=2) + "\n"


